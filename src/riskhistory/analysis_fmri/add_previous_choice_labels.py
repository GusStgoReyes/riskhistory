import pandas as pd
import numpy as np
import os


def categorize_response(response):
    """
    Categorize response into binary accept/reject.
    
    Parameters
    ----------
    response : str
        Response type (strongly_accept, weakly_accept, weakly_reject, strongly_reject)
        
    Returns
    -------
    str
        'accept' or 'reject'
    """
    if pd.isna(response) or response == 'noresp':
        return np.nan
    elif 'accept' in response:
        return 'accept'
    elif 'reject' in response:
        return 'reject'
    else:
        return np.nan


def add_previous_choice_labels(metadata_path, 
                               output_path=None,
                               binary_classification=True,
                               n_back=1):
    """
    Add previous choice labels to trial metadata for MVPA analysis.
    
    Parameters
    ----------
    metadata_path : str
        Path to trial metadata CSV (output from LSA extraction)
    output_path : str or None
        Path to save updated metadata (if None, overwrites original)
    binary_classification : bool
        If True, use binary accept/reject labels
        If False, use 4-way classification (strongly/weakly accept/reject)
    n_back : int
        How many trials back to look (default: 1 for trial n-1)
        
    Returns
    -------
    pd.DataFrame
        Updated metadata with previous choice labels
    """
    # Load metadata
    metadata = pd.read_csv(metadata_path)
    
    print(f"Loaded {len(metadata)} trials from {metadata_path}")
    
    # Sort by subject, run, and onset to ensure correct order
    metadata = metadata.sort_values(['subject', 'run', 'onset']).reset_index(drop=True)
    
    # Initialize columns for previous choice
    for i in range(1, n_back + 1):
        metadata[f'prev_choice_n{i}'] = np.nan
        if binary_classification:
            metadata[f'prev_choice_n{i}_binary'] = np.nan
    
    # Process each subject and run separately
    for subject in metadata['subject'].unique():
        for run in metadata['run'].unique():
            # Get trials for this subject and run
            mask = (metadata['subject'] == subject) & (metadata['run'] == run)
            indices = metadata[mask].index.tolist()
            
            if len(indices) == 0:
                continue
            
            print(f"Processing subject {subject}, run {run}: {len(indices)} trials")
            
            # Add previous choice labels
            for idx_pos, idx in enumerate(indices):
                # Get previous trial indices
                for i in range(1, n_back + 1):
                    if idx_pos >= i:  # Make sure there is a previous trial
                        prev_idx = indices[idx_pos - i]
                        prev_response = metadata.loc[prev_idx, 'response']
                        
                        # Store full response
                        metadata.loc[idx, f'prev_choice_n{i}'] = prev_response
                        
                        # Store binary response if requested
                        if binary_classification:
                            prev_binary = categorize_response(prev_response)
                            metadata.loc[idx, f'prev_choice_n{i}_binary'] = prev_binary
    
    # Add some useful derived columns
    
    # 1. Current choice binary
    if 'response' in metadata.columns:
        metadata['current_choice_binary'] = metadata['response'].apply(categorize_response)
    
    # 2. Switch/repeat indicator (based on binary classification)
    if binary_classification and 'prev_choice_n1_binary' in metadata.columns:
        def is_switch(row):
            if pd.isna(row['prev_choice_n1_binary']) or pd.isna(row['current_choice_binary']):
                return np.nan
            return row['prev_choice_n1_binary'] != row['current_choice_binary']
        
        metadata['is_switch'] = metadata.apply(is_switch, axis=1)
        metadata['is_repeat'] = metadata.apply(
            lambda row: not row['is_switch'] if not pd.isna(row['is_switch']) else np.nan, 
            axis=1
        )
    
    # 3. Add trial number within run for easy reference
    metadata['trial_num_in_run'] = metadata.groupby(['subject', 'run']).cumcount() + 1
    
    # Summary statistics
    print("\n" + "="*60)
    print("Summary Statistics")
    print("="*60)
    
    total_trials = len(metadata)
    trials_with_prev = metadata['prev_choice_n1'].notna().sum()
    
    print(f"Total trials: {total_trials}")
    print(f"Trials with previous choice label: {trials_with_prev}")
    print(f"Trials without previous choice: {total_trials - trials_with_prev} (first trial of each run)")
    
    if binary_classification:
        print("\nBinary classification distribution:")
        print(metadata['prev_choice_n1_binary'].value_counts(dropna=False))
        
        if 'is_switch' in metadata.columns:
            print("\nSwitch/Repeat distribution:")
            switch_count = metadata['is_switch'].sum()
            repeat_count = metadata['is_repeat'].sum()
            print(f"  Switches: {switch_count}")
            print(f"  Repeats: {repeat_count}")
            if switch_count + repeat_count > 0:
                print(f"  Switch rate: {switch_count / (switch_count + repeat_count):.2%}")
    else:
        print("\n4-way classification distribution:")
        print(metadata['prev_choice_n1'].value_counts(dropna=False))
    
    # Save updated metadata
    if output_path is None:
        output_path = metadata_path
    
    metadata.to_csv(output_path, index=False)
    print(f"\nUpdated metadata saved to {output_path}")
    
    return metadata


def create_mvpa_labels_file(metadata_path, 
                            output_dir,
                            classification_type='binary',
                            exclude_first_trials=True):
    """
    Create a simplified labels file specifically for MVPA analysis.
    
    Parameters
    ----------
    metadata_path : str
        Path to updated trial metadata CSV
    output_dir : str
        Directory to save labels file
    classification_type : str
        'binary' for accept/reject or '4way' for all response types
    exclude_first_trials : bool
        Whether to exclude first trial of each run (no previous choice)
        
    Returns
    -------
    pd.DataFrame
        MVPA labels dataframe
    """
    # Load metadata
    metadata = pd.read_csv(metadata_path)
    
    # Select relevant columns for MVPA
    if classification_type == 'binary':
        label_col = 'prev_choice_n1_binary'
        mvpa_cols = ['subject', 'run', 'trial_label', 'beta_path', 
                     'prev_choice_n1_binary', 'current_choice_binary',
                     'is_switch', 'trial_num_in_run']
    else:
        label_col = 'prev_choice_n1'
        mvpa_cols = ['subject', 'run', 'trial_label', 'beta_path',
                     'prev_choice_n1', 'response', 'trial_num_in_run']
    
    # Filter to only include available columns
    mvpa_cols = [col for col in mvpa_cols if col in metadata.columns]
    mvpa_labels = metadata[mvpa_cols].copy()
    
    # Exclude trials without previous choice if requested
    if exclude_first_trials:
        n_before = len(mvpa_labels)
        mvpa_labels = mvpa_labels[mvpa_labels[label_col].notna()].reset_index(drop=True)
        n_after = len(mvpa_labels)
        print(f"Excluded {n_before - n_after} trials without previous choice")
    
    # Save labels file
    os.makedirs(output_dir, exist_ok=True)
    labels_filename = f'mvpa_labels_{classification_type}.csv'
    labels_path = os.path.join(output_dir, labels_filename)
    mvpa_labels.to_csv(labels_path, index=False)
    
    print(f"\nMVPA labels file saved to {labels_path}")
    print(f"Total trials for MVPA: {len(mvpa_labels)}")
    
    if classification_type == 'binary':
        print("\nClass distribution:")
        print(mvpa_labels['prev_choice_n1_binary'].value_counts())
    else:
        print("\nClass distribution:")
        print(mvpa_labels['prev_choice_n1'].value_counts())
    
    return mvpa_labels


